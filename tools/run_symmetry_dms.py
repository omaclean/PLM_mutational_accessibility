"""The symmetry battery on the DMS datasets: influenza (two models) and SARS-CoV-2 (a different model).

    python tools/run_symmetry_dms.py --guide guides/h3n2_13lineage.yaml

Reviewer 2 asked for a crossover: does the influenza fine-tune track the influenza spectrum better than
the SARS-CoV-2 spectrum, and does the SARS-CoV-2 spike model show the reverse? The DMS tables hold, for
each scanned replacement, the score of a base and a fine-tuned model on the scan's own reference sequence,
so both viruses can be tested with real codons held fixed and only the spectrum changed. Each dataset is
scored against its own virus's spectrum and the other's, with the same four amino-acid controls.

Writes ``results/<run>/symmetry_dms_<test>.tsv.gz``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))   # run_symmetry_sim sits beside this script

import numpy as np
import pandas as pd

from mutacc import accessibility as acc
from mutacc import symmetry as sym
from mutacc.guide import REPO_ROOT, load_guide
from run_symmetry_sim import CONTROLS, pair_controls

SEED = 20261009
SPECTRUM = {"MA22": "influenza_h3n2", "Perth09": "influenza_h3n2", "BA2": "sars_cov_2", "XBB15": "sars_cov_2"}
OTHER = {"influenza_h3n2": "sars_cov_2", "sars_cov_2": "influenza_h3n2"}


def build(guide_path: Path) -> tuple[pd.DataFrame, list[str]]:
    g = load_guide(guide_path)
    scores = g.read_table("dms_scores")
    summary = g.read_table("dms_peak_summary")
    role = {(r.dataset, r.model_name): r.model_role for r in summary.drop_duplicates(["dataset", "model_name"]).itertuples()}
    key = ["dataset", "site", "aa"]
    scores = scores.copy()
    scores["role"] = [role[(d, m)] for d, m in zip(scores["dataset"], scores["model_name"])]
    wide = None
    for r in ("base", "finetune"):
        sub = scores[scores["role"] == r][key + ["ref_codon", "nt_steps", "log_plm"]].rename(columns={"log_plm": f"plm_{r}"})
        wide = sub if wide is None else wide.merge(sub[key + [f"plm_{r}"]], on=key, validate="one_to_one")
    wide["ref_aa"] = [acc.GENETIC_CODE[c] for c in wide["ref_codon"]]
    wide = wide.merge(pair_controls(guide_path), on=["ref_aa", "aa"], how="left", validate="many_to_one")
    if wide[CONTROLS].isna().any().any():
        raise ValueError("replacements with no control score")
    wide["position"] = wide["site"]
    wide["lineage"] = wide["dataset"]
    return wide, ["plm_base", "plm_finetune"] + CONTROLS


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--guide", type=Path, default=REPO_ROOT / "guides" / "h3n2_13lineage.yaml")
    ap.add_argument("--n-boot", type=int, default=300)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args(argv)
    g = load_guide(args.guide)
    out_dir = args.out or g.results_dir
    frame, names = build(args.guide)

    orient, flip, direction = [], [], []
    for ds, spec in SPECTRUM.items():
        sub = frame[frame["dataset"] == ds]
        units = sym.units_from_frame(sub, names)
        for label, sname in (("own", spec), ("other", OTHER[spec])):
            q = acc.load_spectrum(REPO_ROOT / "data" / "spectra" / f"{sname}.csv")
            o = sym.orientation_battery(units, q, names, n_boot=args.n_boot, seed=SEED)
            o.insert(0, "dataset", ds); o.insert(1, "which", label); o.insert(2, "spectrum", sname)
            orient.append(o)
            f = sym.flip_null(units, q, names)
            f.insert(0, "dataset", ds); f.insert(1, "which", label); f.insert(2, "spectrum", sname)
            flip.append(f)
            d = sym.direction_contrast(units, q, names, n_boot=args.n_boot, seed=SEED)
            d.insert(0, "dataset", ds); d.insert(1, "which", label); d.insert(2, "spectrum", sname)
            direction.append(d)
        print(ds, spec, "done", flush=True)

    written = []
    for name, parts in (("orientation", orient), ("flip", flip), ("direction", direction)):
        p = out_dir / f"symmetry_dms_{name}.tsv.gz"
        pd.concat(parts).to_csv(p, sep="\t", index=False, float_format="%.8g", compression="gzip")
        written.append(p)
    manifest = out_dir / "MANIFEST.tsv"
    rows = pd.read_csv(manifest, sep="\t").to_dict("records")
    have = {p.name for p in written}
    rows = [r for r in rows if r["file"] not in have]
    for p in written:
        t = pd.read_csv(p, sep="\t")
        rows.append({"file": p.name, "source": f"generated by tools/run_symmetry_dms.py (n_boot={args.n_boot}, seed={SEED})",
                     "source_sha256_16": "", "rows": len(t), "columns": t.shape[1], "dropped": "",
                     "used_for": "Symmetry tests on DMS datasets: crossover across viruses (SYMMETRY_TESTS.md)"})
    pd.DataFrame(rows).sort_values("file").to_csv(manifest, sep="\t", index=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
