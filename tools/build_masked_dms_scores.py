#!/usr/bin/env python3
"""Collapse the masked-marginal profiles into the shipped ``dms_scores_masked`` table.

    python tools/build_masked_dms_scores.py

``dms_scores`` ships one row per (dataset, model, site, replacement) with the model's
probability already computed, because computing it needs a GPU. This writes the masked sibling
of that column in the same shape, so every DMS figure can read the masked marginal from a
shipped table and nothing in ``figures/`` has to touch a 20 x L profile or a model.

Input is the profiles under ``output/unmasked_check/`` (both estimators, one pair of CSVs per
backbone and model, built by ``dev/masked_dms/embed_masked_profile.py`` and
``embed_masked_profile_esmc.py``). Output is
``results/<guide results dir>/dms_scores_masked.tsv.gz`` plus a provenance JSON recording the
gate.

**The gate.** Each profile pair carries an unmasked arm as well as a masked one. Before writing
anything this reproduces the shipped ``log_plm`` from the unmasked arm and fails if the two
disagree by more than ``mutacc.masked_dms.UNMASKED_TOL``. The published figures were drawn from
that column, so reproducing it is what makes masking the only difference between the old
numbers and the new ones. See ``mutacc/masked_dms.py`` for why the choice of estimator matters
at all.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from export_base import append_manifest  # noqa: E402
from mutacc.guide import load_guide  # noqa: E402
from mutacc.masked_dms import (  # noqa: E402
    MASKED_COLUMN, PROFILE_LABEL, UNMASKED_TOL, build_masked_column)

REPO = Path(__file__).resolve().parents[1]
GUIDE = REPO / "guides" / "h3n2_13lineage.yaml"
PROFILES = REPO / "output" / "unmasked_check"
#: The results table this writes. Not ``STEM``: that name is how the figure tests
#: find a *figure* stem that needs a manuscript number, and this is a table.
TABLE = "dms_scores_masked"


def _repo_relative(path: Path) -> str:
    """``path`` as the repository sees it, or its name if it lies outside the repo."""
    path = Path(path).resolve()
    try:
        return path.relative_to(REPO).as_posix()
    except ValueError:
        return path.name


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--guide", type=Path, default=GUIDE)
    ap.add_argument("--results", type=Path, default=None,
                    help="results directory (default: the guide's)")
    ap.add_argument("--profiles", type=Path, default=PROFILES)
    args = ap.parse_args(argv)

    guide = load_guide(args.guide)
    results = args.results or guide.results_dir
    scores = guide.read_table("dms_scores", results)

    masked, worst = build_masked_column(scores, args.profiles)
    print(f"unmasked profile reproduces the shipped log_plm to {worst:.3g} "
          f"(tolerance {UNMASKED_TOL:g})")

    out = Path(results) / f"{TABLE}.tsv.gz"
    masked.to_csv(out, sep="\t", index=False)
    print(f"wrote {out} ({len(masked)} rows, {masked['dataset'].nunique()} backbones)")

    provenance = Path(results) / f"{TABLE}_provenance.json"
    provenance.write_text(json.dumps({
        "table": out.name,
        "rows": int(len(masked)),
        "column": MASKED_COLUMN,
        "arms": [{"dataset": d, "model_name": m, "profile_label": label}
                 for (d, m), label in PROFILE_LABEL.items()],
        # Repo-relative: an absolute path here would be this machine's, not a provenance
        # anyone else could follow, and the repo forbids one in a shipped file.
        "profiles_dir": _repo_relative(args.profiles),
        "unmasked_gate_max_abs_diff": worst,
        "unmasked_gate_tolerance": UNMASKED_TOL,
        "scoring": ("one forward pass per site with that site replaced by the mask token; the "
                    "probability is read at the masked position only, and log10 is taken to "
                    "match the scale of dms_scores.log_plm"),
        "built_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "built_by": "tools/build_masked_dms_scores.py",
    }, indent=2))
    print(f"wrote {provenance.name}")

    # Every shipped table carries a MANIFEST row saying where it came from; a table without
    # one is a file nobody can trace, and test_data_integrity fails on it.
    append_manifest(Path(results) / "MANIFEST.tsv", [{
        "file": out.name,
        # "generated by" is the manifest's way of saying there is no single source file to
        # hash: this table is collapsed from eight profile CSVs, so they are named instead.
        "source": ("generated by tools/build_masked_dms_scores.py from "
                   + _repo_relative(args.profiles) + "/*__masked_profile.csv"),
        "source_sha256_16": "",
        "rows": len(masked),
        "columns": masked.shape[1],
        "dropped": "",
        "used_for": ("Figures 4, SL and SM: the masked marginal for every row of dms_scores "
                     "(log10), the probability those figures report"),
    }])
    return 0


if __name__ == "__main__":
    sys.exit(main())
