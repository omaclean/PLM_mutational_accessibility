#!/usr/bin/env python3
"""The values behind Figure 1B and 1C: every replacement, ranked, under both quantities.

    python tools/export_fig01bc_values.py --comparison K
    python tools/export_fig01bc_values.py <repo> <out_dir> --comparison K   # how the build calls it

Panels B and C are the one part of Figure 1 that is placed as a frozen render
(``data/frozen_panels/fig1bc_ranked_mutations_finetuned_esm2_ha80.pdf``, see
``guides/composites/fig01.yaml``). They therefore had no values table, while panel D --
which is regenerated by ``figures/make_fig01d.py`` -- had one. This script closes that gap
by recomputing what the two panels plot from the repository's own shipped table, so all
three panels of Figure 1 ship with their numbers.

What the panels draw
--------------------
Both panels take one lineage's protein and every single-residue replacement away from it
(19 alternatives at each of the reference's sites), order them by a probability, and plot
log10 of that probability against rank. Panel B orders by the language model's probability
for the replacement; panel C orders by the probability of reaching it under the nucleotide
mutation spectrum, from the lineage's own codon. The replacements that actually separate
the focal lineage from its comparison lineage are marked on both. The two panels are the
same replacements in two different orders, which is the comparison the figure exists to
make, so they are written here as one file with a ``panel`` column rather than as two.

Why the ranks of panel C are not reproducible to the integer
------------------------------------------------------------
Panel B's ordering is effectively total: the model gives 10,753 distinct probabilities to
10,754 replacements. Panel C's is not, and not by a little -- mutational accessibility
depends only on the codon and the target amino acid, so those same 10,754 replacements take
only about 860 distinct values, in tie blocks of up to about thirty. The rendered panel was
drawn with ``DataFrame.sort_values``'s default quicksort, which is not stable, so which
member of a tie block got which rank was decided by an implementation detail of the sort and
is not recoverable from the data.

This file therefore does not pretend to a single integer. ``rank`` is standard competition
ranking (tied replacements share the first rank of their block), and ``rank_tie_first`` and
``rank_tie_last`` give the block's extent. Every one of the labelled ranks baked into the
shipped panel falls inside its block, which is checked by
``tests/test_fig01bc_values.py``; panel B's, having no ties to speak of, reproduce exactly.
A reader comparing a label on the figure against this table should expect agreement on
panel B and agreement to within the tie block on panel C.

Source
------
``replacement_scores`` from the run guide -- the shipped per-replacement table, not the
upstream run directory and not the rendered PDF. The focal lineage is the guide's
``primary_lineage``; the comparison lineage and the model's role are given on the command
line, because nothing that names a lineage or a model may be written into this repository's
figure code.

The marked replacements are derived here, by diffing the two lineages' ``ref_aa`` columns,
and the result is checked against the translation of the focal lineage's root FASTA before
anything is written. That check is not ceremony: diffing a *stale* stored table against a
*live* root FASTA is exactly what put the phantom ``N145S`` into the published 2 Jul 2026
render of these panels (``LINEAGE_DEFINITIONS.md`` section 6).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np                                            # noqa: E402
import pandas as pd                                           # noqa: E402
from Bio.Seq import Seq                                       # noqa: E402

from mutacc.audit import HA_PRECURSOR_OFFSET                  # noqa: E402
from mutacc.guide import REPO_ROOT, GuideError, load_guide    # noqa: E402
from mutacc.io import write_caption, write_values             # noqa: E402

STEM = "fig01bc_ranked_mutations"

#: The guide whose lineage set and models Figure 1B/1C is drawn from.
DEFAULT_GUIDE = REPO_ROOT / "guides" / "h3n2_5lineage.yaml"

#: ``panel`` letter -> (the column it orders by, the name of that quantity). The order is
#: the order the panels sit in on the page, left to right, and the order of the rows.
PANELS = {
    "B": ("plm_prob", "model_probability"),
    "C": ("mut_prob", "mutational_accessibility"),
}

#: Mature position at which the second chain of the cleaved protein begins. The precursor is
#: numbered straight through; the mature numbering the manuscript uses restarts here with its
#: own prefix. Taken from the scoring run that produced the frozen panel, which built its
#: numbering map with this boundary, and pinned by the labels baked into that panel.
SECOND_CHAIN_START = 330

#: Prefix the second chain's sites carry, and the one the residues ahead of the mature
#: protein carry. Both follow the rendered panel's own labels.
SECOND_CHAIN_PREFIX = "HA2:"
PRESEQUENCE_PREFIX = "SP"

#: ``floor`` for log10 of a probability, so that an exact zero becomes a finite number
#: instead of ``-inf``. The value the rendered panels clipped at.
LOG_FLOOR = 1e-32

COLS = [
    "panel", "quantity", "model", "model_label", "model_role",
    "lineage", "comparison_lineage", "position", "site", "ref_aa", "target_aa",
    "mutation", "nt_steps", "value", "log10_value",
    "rank", "rank_tie_first", "rank_tie_last", "n_ranked", "observed",
]


def site_label(position: int) -> str:
    """Mature numbering for a 1-based position in the precursor.

    Three regimes, which is what the rendered panel's labels show: the residues ahead of the
    mature protein count backwards to the cleavage point, the first chain is the precursor
    position less the leader's length, and the second chain restarts from one behind its own
    prefix. Checked against the alignment-derived map for every position of the focal root,
    which it reproduces exactly (``tests/test_fig01bc_values.py``).
    """
    mature = position - HA_PRECURSOR_OFFSET
    if mature < 1:
        # The leader has no mature number of its own, so it counts up to the cleavage point
        # and stops at zero there -- the last residue before mature 1 is SP0, not SP-1.
        return f"{PRESEQUENCE_PREFIX}{mature}"
    if mature < SECOND_CHAIN_START:
        return str(mature)
    return f"{SECOND_CHAIN_PREFIX}{mature - SECOND_CHAIN_START + 1}"


def mutation_label(site: str, ref_aa: str, target_aa: str) -> str:
    """``T328A``, or ``HA2:S49N`` on the second chain.

    The chain prefix leads the whole label rather than sitting between the residue and its
    number, which is how the rendered panel writes it and how the manuscript quotes it.
    """
    chain, _, number = site.rpartition(":")
    prefix = f"{chain}:" if chain else ""
    return f"{prefix}{ref_aa}{number}{target_aa}"


def root_protein(lineage) -> str:
    """The lineage root's protein, translated from its nucleotide FASTA.

    Reads the file the guide names rather than trusting the stored table, because the one
    defect these panels are known to have shipped came from the two disagreeing.
    """
    from Bio import SeqIO

    record = next(iter(SeqIO.parse(lineage.root, "fasta")))
    nucleotides = str(record.seq).replace("-", "").upper()
    return str(Seq(nucleotides[: len(nucleotides) // 3 * 3]).translate()).rstrip("*")


def reference_series(frame: pd.DataFrame, lineage: str) -> pd.Series:
    """``position -> ref_aa`` for one lineage, raising if a position disagrees with itself."""
    rows = frame[frame["lineage"] == lineage]
    if rows.empty:
        raise GuideError(f"no rows for lineage {lineage!r} in the replacement table")
    unique = rows.groupby("position")["ref_aa"].nunique()
    if (unique > 1).any():
        bad = sorted(unique[unique > 1].index)[:10]
        raise GuideError(f"lineage {lineage!r} has more than one ref_aa at position(s) {bad}")
    return rows.groupby("position")["ref_aa"].first()


def observed_replacements(frame: pd.DataFrame, focal: str, comparison: str) -> dict[int, str]:
    """``position -> target amino acid`` for the replacements that separate the two lineages."""
    focal_ref = reference_series(frame, focal)
    other_ref = reference_series(frame, comparison)
    shared = focal_ref.index.intersection(other_ref.index)
    if len(shared) != len(focal_ref) or len(shared) != len(other_ref):
        raise GuideError(
            f"lineages {focal!r} and {comparison!r} are scored at different positions "
            f"({len(focal_ref)} vs {len(other_ref)}, {len(shared)} shared); they cannot be "
            f"diffed position by position"
        )
    return {int(p): str(other_ref[p]) for p in shared if focal_ref[p] != other_ref[p]}


def check_reference_against_root(frame: pd.DataFrame, lineage) -> None:
    """Raise unless the stored ``ref_aa`` still agrees with the root FASTA it describes.

    The failure this guards against is silent and has happened: a root corrected after its
    table was written leaves the table describing a protein that no longer exists, and the
    diff against another lineage then reports replacements that are not there.
    """
    stored = reference_series(frame, lineage.id)
    protein = root_protein(lineage)
    if len(protein) != len(stored):
        raise GuideError(
            f"lineage {lineage.id!r}: the stored table has {len(stored)} positions but "
            f"{lineage.root.name} translates to {len(protein)} residues; the table predates "
            f"an edit to the root. Re-run the scoring step rather than re-exporting."
        )
    disagree = [f"{stored[p]}{p}{protein[p - 1]}" for p in stored.index if stored[p] != protein[p - 1]]
    if disagree:
        raise GuideError(
            f"lineage {lineage.id!r}: the stored table's ref_aa disagrees with "
            f"{lineage.root.name} at {len(disagree)} position(s) ({', '.join(disagree[:10])}). "
            f"The table predates an edit to the root; re-run the scoring step rather than "
            f"re-exporting, or the marked replacements will be wrong."
        )


def rank_panel(rows: pd.DataFrame, column: str) -> pd.DataFrame:
    """Competition ranks for one panel, with the extent of each tie block beside them.

    Sorted descending by the ranked quantity, then by position and target residue, so that
    the file has one order and that order does not depend on how the input happened to be
    sorted. The ranks themselves are computed from the values, not from the row order.
    """
    out = rows.sort_values([column, "position", "aa"], ascending=[False, True, True],
                           kind="mergesort").reset_index(drop=True)
    values = out[column].to_numpy(dtype=float)
    # Competition ranking on a descending sort: the first and last ordinal position at which
    # this value appears. Both are needed because panel C's values are heavily tied and the
    # rendered panel's own rank for a tied replacement is only known to lie between them.
    first = np.searchsorted(-values, -values, side="left") + 1
    last = np.searchsorted(-values, -values, side="right")
    out["rank"] = first
    out["rank_tie_first"] = first
    out["rank_tie_last"] = last
    out["n_ranked"] = len(out)
    out["value"] = values
    out["log10_value"] = np.log10(np.clip(values, LOG_FLOOR, None))
    return out


def build(guide, comparison: str, model_role: str, results: Path | None = None) -> pd.DataFrame:
    """Both panels' rows for one model and one pair of lineages."""
    focal = guide.primary_lineage
    if focal is None:
        raise GuideError(f"{guide.source.name} names no primary_lineage, so the focal "
                         f"lineage of these panels is not defined")
    if comparison == focal:
        raise GuideError(f"the comparison lineage must differ from the focal lineage {focal!r}")
    known = {lin.id: lin for lin in guide.lineages}
    if comparison not in known:
        raise GuideError(f"comparison lineage {comparison!r} is not in {guide.source.name}; "
                         f"it has {sorted(known)}")
    models = [m for m in guide.models if m.role == model_role]
    if len(models) != 1:
        raise GuideError(f"{guide.source.name} has {len(models)} models with role "
                         f"{model_role!r}; exactly one is needed to name the panel's model")
    model = models[0]

    frame = guide.read_table("replacement_scores", results)
    guide.check_lineages(frame["lineage"].unique(), "replacement_scores")
    frame = frame[frame["model"] == model.key]
    if frame.empty:
        raise GuideError(f"replacement_scores has no rows for model {model.key!r}")
    check_reference_against_root(frame, known[focal])

    marked = observed_replacements(frame, focal, comparison)
    if not marked:
        raise GuideError(f"lineages {focal!r} and {comparison!r} have identical reference "
                         f"proteins; these panels have nothing to mark")

    rows = frame[frame["lineage"] == focal]
    parts = []
    for panel, (column, quantity) in PANELS.items():
        part = rank_panel(rows, column)
        part.insert(0, "panel", panel)
        part["quantity"] = quantity
        parts.append(part)
    out = pd.concat(parts, ignore_index=True)

    out["model"] = model.key
    out["model_label"] = model.label
    out["model_role"] = model.role
    out["lineage"] = focal
    out["comparison_lineage"] = comparison
    out["position"] = out["position"].astype(int)
    out["site"] = [site_label(p) for p in out["position"]]
    out = out.rename(columns={"aa": "target_aa"})
    out["mutation"] = [mutation_label(s, r, t) for s, r, t in
                       zip(out["site"], out["ref_aa"], out["target_aa"])]
    out["observed"] = [marked.get(p) == t for p, t in zip(out["position"], out["target_aa"])]
    return out[COLS]


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    # Positional, and both optional: tools/build_figures.py calls a table exporter as
    # ``<script> <repo> <out_dir>`` with no flags at all.
    parser.add_argument("repo", nargs="?", type=Path, default=REPO_ROOT,
                        help="repository root (default: the one this script lives in)")
    parser.add_argument("out_dir", nargs="?", type=Path, default=None,
                        help="where to write the table (default: <repo>/output)")
    parser.add_argument("--guide", type=Path, default=DEFAULT_GUIDE,
                        help="run guide naming the lineages and models")
    parser.add_argument("--comparison", required=True,
                        help="the lineage the focal lineage is compared against; its "
                             "differences from the focal reference are the marked points")
    parser.add_argument("--model-role", default="finetune",
                        help="role of the model whose probabilities the panels show "
                             "(default: the fine-tuned one, which is what the shipped panel "
                             "was rendered from)")
    parser.add_argument("--results", type=Path, default=None,
                        help="read the guide's tables from here instead of its results_dir")
    args = parser.parse_args(argv)
    if args.out_dir is None:
        args.out_dir = args.repo / "output"
    return args


# ---------------------------------------------------------------------------
# The caption. It belongs here rather than in figures/make_fig01bc.py, which draws the
# panels: both would otherwise declare this stem and output/ would have two scripts
# claiming one file (tests/test_output_provenance.py). Everything it quotes comes from
# the table written just above, so nothing is retyped.
# ---------------------------------------------------------------------------

def _extremes(frame: pd.DataFrame, key: str) -> str:
    """"X is the highest at rank N (top P%) and Y the lowest at ..." for one panel."""
    rows = frame[frame["panel"] == key]
    marked = rows[rows["observed"]].sort_values("rank")
    n_ranked = int(rows["n_ranked"].iloc[0])
    best, worst = marked.iloc[0], marked.iloc[-1]
    return (
        f"{best['mutation']} is the highest at rank {int(best['rank'])} "
        f"(top {100 * int(best['rank']) / n_ranked:.1f}%) and {worst['mutation']} the lowest at "
        f"rank {int(worst['rank'])} (top {100 * int(worst['rank']) / n_ranked:.1f}%)"
    )


def caption(frame: pd.DataFrame) -> str:
    """One caption for both panels, as make_fig02ab.py writes one for its pair."""
    rows_c = frame[frame["panel"] == "C"]
    marked_c = rows_c[rows_c["observed"]]
    n_ranked = int(rows_c["n_ranked"].iloc[0])
    widest = int((marked_c["rank_tie_last"] - marked_c["rank_tie_first"]).max()) + 1
    return f"""
    **Every replacement ranked, by the model and by mutational accessibility.** All
    {n_ranked:,} amino-acid replacements available on the J.2 backbone ({n_ranked // 19}
    sites x 19 alternative residues), ordered from the highest value to the lowest on a
    logarithmic scale, with the nine replacements that separate J.2 from subclade K marked
    and labelled with their rank. **(B)** the fine-tuned model's probability:
    {_extremes(frame, 'B')}. **(C)** mutational accessibility: {_extremes(frame, 'C')}.

    Accessibility depends only on the codon and the target residue, so it takes far fewer
    distinct values than there are replacements and panel C's ranks are heavily tied. The
    marked ranks are competition ranks -- a tie takes the first rank of its block -- and the
    widest block holding one of the nine is {widest} replacements deep, which is why two of
    them share a rank. Panel B's ordering has no ties among the nine.
    """



def main(argv=None) -> int:
    args = parse_args(argv)
    guide = load_guide(args.guide)
    table = build(guide, args.comparison, args.model_role, args.results)
    path = write_values(table, args.out_dir, STEM)
    write_caption(caption(table), args.out_dir, STEM)
    marked = table[table["observed"]]
    print(f"wrote {path} ({len(table)} rows, {len(marked) // len(PANELS)} marked replacements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
