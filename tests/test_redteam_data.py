@pytest.mark.parametrize("name", sorted(GUIDES))
def test_roots_start_with_atg_and_have_no_internal_stop_or_gap_in_the_protein(name):
    for lin in GUIDES[name].lineages:
        seq = fasta_seq(lin.root)
        assert len(seq) % 3 == 0, lin.id
        codons = [seq[i:i + 3] for i in range(0, len(seq), 3)]
        assert codons[0] == "ATG", f"{lin.id}: starts with {codons[0]}"
        assert not STOPS & set(codons[:-1]), lin.id


@pytest.mark.parametrize("name", sorted(GUIDES))
def test_roots_are_pairwise_distinct_sequences(name):
    guide = GUIDES[name]
    seqs = {lin.id: fasta_seq(lin.root) for lin in guide.lineages}
    ids = list(seqs)
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            diffs = sum(x != y for x, y in zip(seqs[a], seqs[b]))
            assert diffs > 0, f"{a} and {b} have identical roots"


@pytest.mark.parametrize("name", sorted(GUIDES))
def test_scored_positions_are_1_to_n_codons_with_no_gap_and_ref_aa_is_the_roots_translation(name):
    """The numbering check: position p must be codon p of the root (1-based), in every lineage."""
    guide = GUIDES[name]
    scores = guide.read_table("replacement_scores")
    for lin in guide.lineages:
        sub = scores[(scores["lineage"] == lin.id) & (scores["model"] == guide.models[0].key)]
        seq = fasta_seq(lin.root)
        n_codons = len(seq) // 3
        positions = np.sort(sub["position"].unique())
        assert positions[0] == 1, f"{lin.id}: positions start at {positions[0]}"
        assert (np.diff(positions) == 1).all(), f"{lin.id}: positions have a gap"
        assert positions[-1] in (n_codons, n_codons - 1), f"{lin.id}: last position {positions[-1]} of {n_codons} codons"
        codons = dict(zip(positions, A.reference_codons(lin.root, positions)))
        translated = sub["position"].map(codons).map(A.GENETIC_CODE)
        bad = sub[translated != sub["ref_aa"]]
        assert bad.empty, f"{lin.id}: ref_aa disagrees with the root at positions {sorted(bad['position'].unique())[:8]}"
        assert (sub["position"].map(codons).map(A.GENETIC_CODE) != "*").all(), f"{lin.id}: a scored site is a stop"


def test_the_16_residue_offset_between_ha0_and_ha1_numbering_is_applied_exactly_once(dms):
    """DMS sites in HA1 numbering (MA22) sit 16 residues after the root's HA0 numbering; Perth09's are HA0.

    For each influenza scan, the offset at which the scan's reference codons best match the root
    must be the one the dataset's numbering implies, and the match at that offset must be high. An
    offset applied twice (32) or not at all (0 for MA22) would match at chance.
    """
    root = fasta_seq(next(l for l in G13.lineages if l.id == "K").root)
    codons = [root[i:i + 3] for i in range(0, len(root), 3)]
    expected = {"MA22": 16, "Perth09": 0}
    floor = {"MA22": 0.9, "Perth09": 0.75}
    for ds, offset in expected.items():
        u = dms[dms["dataset"] == ds].drop_duplicates("site")
        rate = {}
        for off in range(-40, 41):
            idx = u["site"].to_numpy() + off
            ok = (idx >= 1) & (idx <= len(codons))
            rate[off] = np.mean([codons[i - 1] == c for i, c, k in zip(idx, u["ref_codon"], ok) if k])
        best = max(rate, key=rate.get)
        assert best == offset, f"{ds}: best offset {best} ({rate[best]:.2f}), expected {offset}"
        assert rate[offset] >= floor[ds], f"{ds}: only {rate[offset]:.2f} of reference codons match at offset {offset}"
        wrong = [rate[o] for o in range(-40, 41) if o != offset]
        assert max(wrong) < 0.5 * rate[offset], f"{ds}: the offset is not clearly identified"


