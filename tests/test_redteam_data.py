def manifest_rows(guide):
    manifest = pd.read_csv(guide.results_dir / "MANIFEST.tsv", sep="\t")
    names = {rel.name for rel in guide.tables.values()}
    return manifest[manifest["file"].isin(names)]


@pytest.mark.parametrize("name", sorted(GUIDES))
def test_manifest_row_and_column_counts_match_the_shipped_tables(name):
    guide = GUIDES[name]
    rows = manifest_rows(guide)
    assert len(rows) == len(guide.tables), "every table the guide names needs exactly one MANIFEST row"
    assert not rows["file"].duplicated().any()
    for r in rows.itertuples():
        frame = pd.read_csv(guide.results_dir / r.file, sep="\t")
        assert (len(frame), frame.shape[1]) == (r.rows, r.columns), r.file
        dropped = [c for c in str(r.dropped).split(",") if c and c != "nan"]
        assert not set(dropped) & set(frame.columns), f"{r.file}: a column listed as dropped is still there"


@pytest.mark.parametrize("name", sorted(GUIDES))
def test_manifest_hash_fields_are_well_formed_and_sources_are_relative(name):
    """Exported tables carry a 16-hex-digit source hash; tables generated inside this repository
    (source text starts with "generated by") have no external source and an empty hash."""
    rows = manifest_rows(GUIDES[name])
    for r in rows.itertuples():
        source, digest = str(r.source), ("" if pd.isna(r.source_sha256_16) else str(r.source_sha256_16))
        if source.startswith("generated by"):
            assert digest == "", f"{r.file}: a generated table has no source file to hash"
            continue
        assert re.fullmatch(r"[0-9a-f]{16}", digest), r.file
        assert not source.startswith(("/", "~")) and ".." not in source.split("/"), r.file
    # one source may feed several tables, but a hash may not be shared by two different sources
    ext = rows[~rows["source"].astype(str).str.startswith("generated by")]
    assert (ext.groupby("source_sha256_16")["source"].nunique() == 1).all()


def test_the_manifest_hash_scheme_is_reproducible(tmp_path):
    """tools/export_tables.sha256 is a 16-hex-digit prefix of the SHA-256 of the file bytes."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("export_tables_rt", REPO_ROOT / "tools" / "export_tables.py")
    mod = importlib.util.module_from_spec(spec)
    import sys
    sys.path.insert(0, str(REPO_ROOT / "tools"))
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(REPO_ROOT / "tools"))
    f = tmp_path / "x.bin"
    f.write_bytes(b"abc" * 100000)
    assert mod.sha256(f) == hashlib.sha256(b"abc" * 100000).hexdigest()[:16]


