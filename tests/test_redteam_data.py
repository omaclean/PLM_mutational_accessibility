def test_symmetry_tables_are_finite_with_sensible_ranges():
    for path in sorted(G13.results_dir.glob("symmetry_*_flip.tsv.gz")):
        t = pd.read_csv(path, sep="\t")
        assert t["pct_flip"].between(1 / 64 - 1e-9, 1).all(), path.name
    for path in sorted(G13.results_dir.glob("symmetry_*_null.tsv.gz")):
        t = pd.read_csv(path, sep="\t")
        assert t["pct_relabel"].between(1 / 24 - 1e-9, 1).all() and t["pct_shuffle"].between(0, 1).all(), path.name
    for path in sorted(G13.results_dir.glob("symmetry_*_direction.tsv.gz")):
        t = pd.read_csv(path, sep="\t")
        assert np.isfinite(t[["contrast", "lo", "hi"]].to_numpy(float)).all(), path.name
        assert (t["lo"] <= t["hi"]).all(), path.name
        truth = t[t["score"] == "accessibility (truth)"]
        assert np.allclose(truth["fraction_of_truth"], 1.0), path.name


